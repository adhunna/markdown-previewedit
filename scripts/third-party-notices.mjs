// Writes THIRD_PARTY_NOTICES.md: every npm package bundled into the VSIX, with its licence text.
// Usage: node scripts/third-party-notices.mjs [--check]   (--check fails if the file is out of date)
import * as esbuild from 'esbuild';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUTPUT = 'THIRD_PARTY_NOTICES.md';
const LICENCE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'LICENCE.md', 'license', 'license.md', 'License.md', 'LICENSE-MIT'];

// Same entry points and platforms as esbuild.mjs.
const BUNDLES = [
  { entryPoints: ['src/extension.ts'], platform: 'node', format: 'cjs', external: ['vscode', 'bufferutil', 'utf-8-validate'] },
  { entryPoints: ['src/preview/mermaid.ts'], platform: 'browser', format: 'iife' },
  { entryPoints: ['src/edit/toolbar.ts'], platform: 'browser', format: 'iife' },
];

const packageDirs = new Set(['node_modules/katex']); // KaTeX CSS and fonts are inlined into dist/katex-inline.css
for (const options of BUNDLES) {
  const result = await esbuild.build({ ...options, bundle: true, write: false, metafile: true, logLevel: 'silent' });
  for (const input of Object.keys(result.metafile.inputs)) {
    const match = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
    if (match) packageDirs.add(match[1]);
  }
}

const packages = new Map();
for (const dir of packageDirs) {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const licenceFile = LICENCE_FILES.map((name) => join(dir, name)).find((path) => existsSync(path));
  const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  packages.set(`${pkg.name}@${pkg.version}`, {
    name: pkg.name,
    version: pkg.version,
    licence: typeof pkg.license === 'string' ? pkg.license : 'see licence text',
    source: (repository ?? pkg.homepage ?? `https://www.npmjs.com/package/${pkg.name}`).replace(/^git\+/, '').replace(/^github:/, 'https://github.com/').replace(/^git(\+https|\+ssh)?:\/\/(git@)?/, 'https://').replace(/\.git$/, ''),
    text: licenceFile ? readFileSync(licenceFile, 'utf8').trim() : `Licensed under ${pkg.license}. No licence file is included in the package; see ${pkg.name} on npm.`,
  });
}

const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const lines = [
  '# Third-party notices',
  '',
  'MarkDownPreview bundles the open-source packages below into its VS Code extension (`.vsix`). Each is used under its own licence, reproduced in full.',
  '',
  '> Generated by `npm run notices` from the build inputs — do not edit by hand.',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...sorted.map((p) => `| [${p.name}](${p.source}) | ${p.version} | ${p.licence} |`),
  '',
  ...sorted.flatMap((p) => ['---', '', `## ${p.name} ${p.version}`, '', `Licence: ${p.licence} · Source: ${p.source}`, '', '```text', p.text.replace(/```/g, "'''"), '```', '']),
];
const content = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : '';
  if (current !== content) {
    console.error(`${OUTPUT} is out of date. Run "npm run notices" and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUTPUT} is up to date (${sorted.length} packages).`);
} else {
  writeFileSync(OUTPUT, content);
  console.log(`Wrote ${OUTPUT} (${sorted.length} packages).`);
}
